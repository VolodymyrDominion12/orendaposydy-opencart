-- Схема бази 3.0.3.2 → 3.0.4.1. Звірено db/schema.sql з install/opencart.sql
-- офіційного пакета 3.0.4.1 (2026-11-06): єдина реальна відмінність ядра —
-- `oc_event.sort_order` отримав DEFAULT 0. Upgrade-скрипти 1000–1009 пакета на
-- базі 3.0.3.2 даних не змінюють (усі кроки під перевірками на старі таблиці/колонки);
-- нових налаштувань і подій у чистій 3.0.4.1 порівняно з нашою базою немає.
-- Офіційний майстер install/ НЕ запускаємо: скрипт 1009 переписує DIR_* у
-- config.php на стандартний system/storage/ — на проді це зламало б storage_kozak/.
--
-- Плюс прибирання: мертва подія sms_alert (контролер видалено раніше).
-- Ідемпотентно: повторний запуск нічого не ламає.
-- ---------------------------------------------------------------------------

ALTER TABLE `{{PREFIX}}event` MODIFY `sort_order` INT(3) NOT NULL DEFAULT 0;

DELETE FROM `{{PREFIX}}event`
 WHERE `code` = 'sms_alert'
   AND `action` = 'extension/module/sms_alert';
