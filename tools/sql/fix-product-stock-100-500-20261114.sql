-- Тимчасові демо-залишки на складі (100–500 шт) для всіх реальних товарів,
-- де зараз стоїть залишок < 100 (зокрема дефолтні 1 шт після імпорту).
-- Детермінований розподіл: 100, 150, 200, 250, 300, 350, 400, 450, 500.
-- Таблиці каталогу — MyISAM (без транзакцій): перед виконанням на проді зробіть експорт БД у phpMyAdmin.
SET NAMES utf8mb4;

UPDATE `{{PREFIX}}product`
   SET `quantity` = 100 + (((`product_id` * 7) % 9) * 50),
       `date_modified` = NOW()
 WHERE `model` <> 'MOCK'
   AND (`quantity` < 100 OR `quantity` > 500);
