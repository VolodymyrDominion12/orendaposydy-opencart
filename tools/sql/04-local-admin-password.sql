-- ---------------------------------------------------------------------------
-- 04. Локальний пароль адміністратора (НЕОБОВ'ЯЗКОВО, але зручно)
--
-- Після імпорту бойової бази в адмінку веде бойовий пароль. Це погано з двох
-- причин:
--   * ви вводите справжній пароль від продакшену на незахищеному localhost;
--   * якщо пароль змінять на проді — локально ви застрягнете.
--
-- Цей скрипт ставить передбачуваний ЛОКАЛЬНИЙ пароль.
--
-- Формула хеша перевірена по коду OpenCart 3.0.3.9
-- (admin/model/user/user.php, рядок 18):
--     password = sha1(salt . sha1(salt . sha1(password_у_відкритому_вигляді)))
--
-- Сіль і хеш рахуються через змінні @local_salt / @local_password, а не через
-- підзапити до тієї ж таблиці. Причина: MySQL при UPDATE ... SET a = ..., b = f(a)
-- обчислює вирази не завжди так, як ви очікуєте, і пароль може вийти недійсним.
-- Зі змінними порядок обчислення однозначний.
--
-- Логін лишається той, що був на проді (скрипт міняє тільки пароль).
-- Пароль: localadmin123  — змініть нижче, якщо хочете інший.
-- ---------------------------------------------------------------------------

SET @local_password = 'localadmin123';
SET @local_salt     = SUBSTRING(MD5(RAND()), 1, 9);

UPDATE `{{PREFIX}}user`
SET `salt`     = @local_salt,
    `password` = SHA1(CONCAT(@local_salt, SHA1(CONCAT(@local_salt, SHA1(@local_password))))),
    `code`     = ''
WHERE `user_id` = 1;

-- Показати, який логін тепер має локальний пароль
SELECT `user_id`, `username`, `firstname`, `lastname`, `email`
FROM `{{PREFIX}}user` WHERE `user_id` = 1;
