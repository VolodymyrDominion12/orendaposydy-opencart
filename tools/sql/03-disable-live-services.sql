-- 03. Вимкнути все, що «дзвонить назовні»
--
-- Після імпорту бойової бази локальний магазин має бойові ключі платіжних
-- систем, доставки, captcha й аналітики. Наслідки, якщо це не вимкнути:
--
--   * платіжний модуль (LiqPay / WayForPay / Приват24) піде на РЕАЛЬНИЙ API
--     з реальними ключами клієнта;
--   * Google reCAPTCHA відхилить форму, бо домен localhost не дозволений —
--     ви не зможете протестувати оформлення замовлення й вирішите, що
--     «на локалі щось зламалося»;
--   * аналітика й ремаркетинг запишуть локальні візити в реальну статистику;
--   * MaxMind (fraud) спробує Завантажити базу й повідомити про помилку в логах.
--
-- Що ми НЕ чіпаємо: module_* (банери, карусель, рекомендовані) — саме їх ви
-- й дивитесь, коли правите верстку.
--
-- Вимкнення — це `_status = 0`, а не видалення. Нічого не втрачається:
-- щоб увімкнути назад, поставте 1 (або зробіть це в адмінці).
-- ---------------------------------------------------------------------------

-- 3.1. Платіжні модулі.
UPDATE `{{PREFIX}}setting` SET `value` = '0'
WHERE `key` LIKE 'payment\_%\_status';

-- 3.2. Модулі доставки (деякі теж ходять на API перевізника).
UPDATE `{{PREFIX}}setting` SET `value` = '0'
WHERE `key` LIKE 'shipping\_%\_status';

-- 3.3. Аналітика, маркетинг, фіди, captcha, антифрод.
-- Фільтр за префіксом типу розширення — це стандартна схема ключів OpenCart
-- (<type>_<code>_status), тому він не залежить від конкретного набору модулів
-- на вашому сайті.
UPDATE `{{PREFIX}}setting` SET `value` = '0'
WHERE `key` REGEXP '^(analytics|marketing|feed|captcha|fraud)_'
  AND `key` LIKE '%\_status';

-- 3.4. Показати, що саме вимкнулось — щоб не було «магії».
SELECT `key`, `value` FROM `{{PREFIX}}setting`
WHERE `key` LIKE 'payment\_%\_status'
   OR `key` LIKE 'shipping\_%\_status'
   OR (`key` REGEXP '^(analytics|marketing|feed|captcha|fraud)_' AND `key` LIKE '%\_status')
ORDER BY `key`;
