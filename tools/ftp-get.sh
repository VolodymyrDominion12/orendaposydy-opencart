#!/bin/bash
# ---------------------------------------------------------------------------
# Забрати один файл із прода через FTP (використовується для бекапу).
#
# Використання:  tools/ftp-get.sh <шлях-на-сайті> <куди-зберегти>
#
# Повертає ненульовий код, якщо файлу на сервері немає — deploy.sh
# трактує це як «новий файл» і це нормально.
# ---------------------------------------------------------------------------

. "$(dirname "$0")/lib.sh"
load_env
require_ftp

REL="$1"
OUT="$2"

[ -n "$REL" ] && [ -n "$OUT" ] || die "Використання: ftp-get.sh <шлях-на-сайті> <куди-зберегти>"

mkdir -p "$(dirname "$OUT")"

# shellcheck disable=SC2046
curl $(ftp_opts) --fail -o "$OUT" "$(ftp_url "$REL")" 2>/dev/null || exit 1

[ -s "$OUT" ] || exit 1
exit 0
